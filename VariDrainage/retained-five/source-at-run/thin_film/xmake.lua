-- thin_film: soap-film thickness, drainage, surface flow and black films (header-only; depends only on vf_core).
-- Included from the root xmake.lua; paths here are relative to thin_film/.
-- The binaries use CHOLMOD (SuiteSparse, with OpenBLAS) for the in-plane preconditioner (VF_HAVE_CHOLMOD;
-- ThinFilmMechanics.h); without it the preconditioner falls back to Eigen's simplicial LDL^T.
add_requires("suitesparse", {configs = {graphblas = false}})

target("vf_thinfilm")
    set_kind("headeronly")
    add_includedirs("include", {public = true})
    add_headerfiles("include/(vf/thinfilm/*.h)")
    add_deps("vf_core")

-- cholmod.h lives in include/suitesparse
local function thin_film_binary(name, file, group)
    target(name)
        set_kind("binary")
        set_group(group)
        add_files(file)
        add_deps("vf_thinfilm")
        add_packages("eigen", "tbb", "suitesparse")
        add_defines("VF_HAVE_CHOLMOD")
        on_load(function (target)
            local pkg = target:pkg("suitesparse")
            if pkg and pkg:installdir() then
                target:add("includedirs", path.join(pkg:installdir(), "include", "suitesparse"))
            end
        end)
    target_end()
end

